import {
  type DateStr,
  type Weekday,
  addDays,
  daysInMonth,
  diffDays,
  maxDate,
  minDate,
  monthsBetween,
  parseDate,
  startOfWeek,
  weekdayOf,
} from "./dates";
import type { Recurrence, TaskFields, TaskVersion } from "./types";

/** Does `rule`, anchored at `anchor`, produce an occurrence on `date`? */
export function ruleMatches(rule: Recurrence, anchor: DateStr, date: DateStr): boolean {
  if (date < anchor) return false;
  switch (rule.type) {
    case "none":
      return date === anchor;
    case "daily":
      return diffDays(anchor, date) % Math.max(1, rule.interval) === 0;
    case "weekly": {
      if (!rule.weekdays.includes(weekdayOf(date))) return false;
      const weeks = diffDays(startOfWeek(anchor), startOfWeek(date)) / 7;
      return weeks % Math.max(1, rule.interval) === 0;
    }
    case "monthly": {
      const months = monthsBetween(anchor, date);
      if (months % Math.max(1, rule.interval) !== 0) return false;
      const { y, m, d } = parseDate(date);
      const dim = daysInMonth(y, m);
      if (rule.monthly.mode === "dayOfMonth") {
        return d === Math.min(rule.monthly.day, dim);
      }
      if (weekdayOf(date) !== rule.monthly.weekday) return false;
      return rule.monthly.nth === -1 ? d + 7 > dim : Math.ceil(d / 7) === rule.monthly.nth;
    }
  }
}

/** Inclusive date window in which a version can generate occurrences (null if empty). */
export function versionWindow(
  v: Pick<TaskVersion, "startDate" | "untilDate" | "effectiveFrom" | "effectiveTo" | "recurrence">,
): { start: DateStr; end: DateStr | null } | null {
  const start = maxDate(v.startDate, v.effectiveFrom);
  let end: DateStr | null = v.untilDate;
  if (v.effectiveTo) end = end ? minDate(end, v.effectiveTo) : v.effectiveTo;
  if (v.recurrence.type === "none") end = end ? minDate(end, v.startDate) : v.startDate;
  if (end && end < start) return null;
  return { start, end };
}

export function versionGenerates(v: TaskVersion, date: DateStr): boolean {
  const w = versionWindow(v);
  if (!w || date < w.start || (w.end && date > w.end)) return false;
  return ruleMatches(v.recurrence, v.startDate, date);
}

/** All dates generated by a version inside [rangeStart, rangeEnd]. */
export function expandVersion(v: TaskVersion, rangeStart: DateStr, rangeEnd: DateStr): DateStr[] {
  const w = versionWindow(v);
  if (!w) return [];
  const start = maxDate(rangeStart, w.start);
  const end = w.end ? minDate(rangeEnd, w.end) : rangeEnd;
  if (end < start) return [];
  const rule = v.recurrence;
  if (rule.type === "none") return start <= v.startDate && v.startDate <= end ? [v.startDate] : [];
  const out: DateStr[] = [];
  if (rule.type === "daily") {
    const step = Math.max(1, rule.interval);
    const offset = diffDays(v.startDate, start);
    let first = offset <= 0 ? v.startDate : addDays(v.startDate, Math.ceil(offset / step) * step);
    while (first <= end) {
      out.push(first);
      first = addDays(first, step);
    }
    return out;
  }
  for (let d = start; d <= end; d = addDays(d, 1)) {
    if (ruleMatches(rule, v.startDate, d)) out.push(d);
  }
  return out;
}

/** Next `count` occurrence dates for unsaved form fields (used for previews). */
export function previewDates(
  fields: Pick<TaskFields, "recurrence" | "startDate" | "untilDate">,
  from: DateStr,
  count: number,
  horizonDays = 800,
): DateStr[] {
  const pseudo = {
    ...fields,
    effectiveFrom: fields.startDate,
    effectiveTo: null,
  } as unknown as TaskVersion;
  const w = versionWindow(pseudo);
  if (!w) return [];
  const out: DateStr[] = [];
  let d = maxDate(from, w.start);
  const last = addDays(d, horizonDays);
  while (out.length < count && d <= last && (!w.end || d <= w.end)) {
    if (ruleMatches(fields.recurrence, fields.startDate, d)) out.push(d);
    d = addDays(d, 1);
  }
  return out;
}

/** Largest number of occurrences the rule can place in one Monday–Sunday week. */
export function maxPerWeek(rule: Recurrence): number {
  switch (rule.type) {
    case "none":
      return 1;
    case "daily":
      return Math.ceil(7 / Math.max(1, rule.interval));
    case "weekly":
      return new Set(rule.weekdays).size;
    case "monthly":
      return 1;
  }
}

export function isRecurring(rule: Recurrence): boolean {
  return rule.type !== "none";
}

/** Every weekday, sorted, de-duplicated. */
export function normalizeWeekdays(days: number[]): Weekday[] {
  return [...new Set(days.filter((d) => Number.isInteger(d) && d >= 1 && d <= 7))].sort(
    (a, b) => a - b,
  ) as Weekday[];
}

